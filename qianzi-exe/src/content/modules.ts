/**
 * 六个模块的定义。
 *
 * 一条原则：**模块只决定「这一句在网站里被讲成什么」，不决定「这一句在原书里的意思」**。
 * 每句的释义、视角分类都在 qianzi.ts 里逐句写死，改模块不会改动任何一句原文的含义。
 */

export type ModuleId = 'cosmos' | 'nature' | 'civilization' | 'human' | 'daily'

export interface ModuleDef {
  id: ModuleId
  /** 章节编号，01 - 05（完整全景是 06，不是一组新的句子） */
  index: string
  /** 章节名：出现在导航、章节标题与影片角标上 */
  name: string
  /** 副名：这个模块具体在看什么 */
  nameZh: string
  /** 一句话：这个模块在看什么 */
  question: string
  /** 这个模块的视觉世界坐标（在同一个世界里连续排布） */
  region: { x: number; y: number; w: number; h: number }
  /** 模块主色 */
  hue: string
  /** 科学说明 / 读法限定 */
  caveat: string
}

