/**
 * 知识网络的边：两句共享至少一个语义标签就连一条边。
 *
 * 这是**本站生成的关联**，不是《千字文》原有的结构；
 * 界面上会明确写成「按语义标签生成的关联」。
 */
export interface Edge {
  a: number
  b: number
  /** 共享的标签 */
  shared: string[]
}

export const EDGES: Edge[] = (() => {
  const out: Edge[] = []
  for (let a = 0; a < PHRASES.length; a += 1) {
    for (let b = a + 1; b < PHRASES.length; b += 1) {
      const shared = PHRASES[a].tags.filter((t) => PHRASES[b].tags.includes(t))
      if (shared.length) out.push({ a, b, shared })
    }
  }
  return out
})()

/** 与某句相关（共享标签）的其它句子，按共享标签数排序 */
export function relatedPhrases(index: number, limit = 8): Phrase[] {
  const p = PHRASES[index]
  if (!p) return []
  const scored = PHRASES.filter((q) => q.i !== p.i).map((q) => ({
    q,
    n: q.tags.filter((t) => p.tags.includes(t)).length,
  }))
  return scored
    .filter((s) => s.n > 0)
    .sort((a, b) => b.n - a.n || a.q.i - b.q.i)
    .slice(0, limit)
    .map((s) => s.q)
}
